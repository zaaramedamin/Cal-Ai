#: One row per food with open reports, worst first.
#:
#: `reports` is the count of *distinct people*, which is the number that decides
#: what to look at. Five reports from one account is one person being persistent;
#: two from two accounts is a food that is probably wrong.
#:
#: The macro-implied calorie figure is repeated from `review_queue` on purpose.
#: "Reads 250 kcal, macros imply 180" is the single most useful thing to know
#: about a food somebody says is wrong, and computing it here means the reviewer
#: never has to do the arithmetic — or get it wrong doing it.
REPORTED_FOODS_VIEW = """
CREATE OR REPLACE VIEW reported_foods AS
SELECT f.id                                              AS food_id,
       min(r.created_at)                                 AS first_reported_at,
       count(DISTINCT r.reporter_id)                     AS reporters,
       count(*)                                          AS reports,
       string_agg(DISTINCT r.reason, ', ' ORDER BY r.reason) AS reasons,
       string_agg(r.note, ' | ') FILTER (WHERE r.note IS NOT NULL) AS notes,
       f.name,
       f.brand,
       f.source,
       f.kcal,
       f.protein_g,
       f.carbs_g,
       f.fat_g,
       ROUND((4 * f.protein_g + 4 * f.carbs_g + 9 * f.fat_g)::numeric, 0)
                                                         AS kcal_implied_by_macros,
       f.withdrawn_at,
       u.email                                           AS food_author
FROM food_reports r
JOIN foods f ON f.id = r.food_id
LEFT JOIN users u ON u.id = f.owner_id
WHERE r.status = 'open'
GROUP BY f.id, u.email
ORDER BY count(DISTINCT r.reporter_id) DESC, min(r.created_at)
"""


